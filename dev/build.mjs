/**
 * Build driver: src/**.ts(x) → the files the Hermes runtime actually loads.
 *
 *   src/sidecar/**        → sidecar/**       (ESM, unbundled, one file per module)
 *   src/scripts/**        → scripts/**       (ESM, unbundled)
 *   src/tests/**          → tests/**         (ESM, unbundled)
 *   src/desktop/plugin.tsx → desktop/plugin.js  (single-file bundle)
 *
 * The desktop half MUST stay a single bundle ≤512 KiB that imports only
 * @hermes/plugin-sdk / react / react/jsx-runtime — the runtime loader
 * (apps/desktop/src/contrib/runtime-loader.ts) reads one file and rewrites
 * those three specifiers. Everything else is inlined by esbuild.
 */
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')

const GENERATED = '// GENERATED — edit src/, then run `node dev/build.mjs`. Do not edit this file.'

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, out)
    else if (/\.(mts|tsx?)$/.test(entry.name) && !entry.name.endsWith('.d.ts')) out.push(full)
  }
  return out
}

const groups = [
  { src: path.join(root, 'src/sidecar'), outbase: path.join(root, 'src/sidecar'), outdir: path.join(root, 'sidecar') },
  { src: path.join(root, 'src/scripts'), outbase: path.join(root, 'src/scripts'), outdir: path.join(root, 'scripts') },
  { src: path.join(root, 'src/tests'), outbase: path.join(root, 'src/tests'), outdir: path.join(root, 'tests') }
]

// `.mts` must land as `.mjs` (the runtime and every import specifier say .mjs),
// while vendor `.ts` must stay `.js` (imports say './vendor/atvv/session.js').
// esbuild maps output *extension* only, so the two kinds cannot share a build call.
// A stale `.js` next to an `.mts` source is the failure mode where `.mjs`
// specifiers silently resolve to a pre-migration file — delete it, loudly.
let built = 0
for (const group of groups) {
  const all = walk(group.src)
  const fromMts = all.filter((f) => f.endsWith('.mts'))
  const fromTs = all.filter((f) => !f.endsWith('.mts'))

  for (const src of fromMts) {
    const stale = path.join(group.outdir, path.relative(group.outbase, src).replace(/\.mts$/, '.js'))
    if (fs.existsSync(stale)) {
      fs.rmSync(stale)
      console.warn(`removed stale ${path.relative(root, stale)} (source is .mts → .mjs)`)
    }
  }

  for (const [entries, outExtension] of [[fromMts, { '.js': '.mjs' }], [fromTs, undefined]]) {
    if (entries.length === 0) continue
    await build({
      entryPoints: entries,
      outbase: group.outbase,
      outdir: group.outdir,
      bundle: false,
      format: 'esm',
      platform: 'node',
      target: 'node22',
      sourcemap: false,
      logLevel: 'warning',
      banner: { js: GENERATED },
      ...(outExtension ? { outExtension } : {})
    })
    built += entries.length
  }
  if (all.length > 0) console.log(`built ${all.length} file(s) → ${path.relative(root, group.outdir)}/`)
}

// ── desktop half: one bundled file, externals only ────────────────────────
const desktopEntry = path.join(root, 'src/desktop/plugin.tsx')
if (fs.existsSync(desktopEntry)) {
  const out = path.join(root, 'desktop/plugin.js')
  await build({
    entryPoints: [desktopEntry],
    outfile: out,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
    logLevel: 'warning',
    banner: { js: GENERATED }
  })
  const bytes = fs.statSync(out).size
  const hash = createHash('sha256').update(fs.readFileSync(out)).digest('hex').slice(0, 12)
  console.log(`built desktop bundle → desktop/plugin.js (${(bytes / 1024).toFixed(1)} KiB, sha256:${hash})`)
  if (bytes > 512 * 1024) {
    console.error('FAIL: desktop bundle exceeds the 512 KiB runtime-loader limit')
    process.exit(1)
  }
  built += 1
} else {
  console.warn('warning: src/desktop/plugin.tsx missing — desktop bundle not built')
}

console.log(`build: ok (${built} module(s))`)
